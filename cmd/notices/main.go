// Command notices assembles the licenses of packages linked into the CLI and
// acceptance application, plus the Go standard library, from local module source.
package main

import (
	"bytes"
	"crypto/sha256"
	_ "embed"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct{ Path, Version, Dir string }
type dependency struct{ Module *module }

//go:embed supplements.json
var supplementData []byte

type supplement struct {
	Module  string `json:"module"`
	Version string `json:"version"`
	Source  string `json:"source"`
	SHA256  string `json:"sha256"`
	Start   string `json:"start"`
	End     string `json:"end"`
}

// embeddedNotice accepts only explicitly reviewed upstream text; dependency or
// source drift requires a new review rather than silently dropping attribution.
func embeddedNotice(m module, s supplement) (string, error) {
	if m.Version != s.Version {
		return "", fmt.Errorf("embedded notice review required for %s %s", m.Path, m.Version)
	}
	data, err := os.ReadFile(filepath.Join(m.Dir, s.Source))
	if err != nil {
		return "", err
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != s.SHA256 {
		return "", fmt.Errorf("embedded notice source changed: %s/%s", m.Path, s.Source)
	}
	text := string(data)
	start := strings.Index(text, s.Start)
	if start < 0 {
		return "", errors.New("reviewed embedded notice start missing")
	}
	end := strings.Index(text[start:], s.End)
	if end < 0 {
		return "", errors.New("reviewed embedded notice end missing")
	}
	var lines []string
	for _, line := range strings.Split(text[start:start+end+len(s.End)], "\n") {
		if !strings.HasPrefix(line, "//") {
			return "", errors.New("reviewed notice contains non-comment source")
		}
		lines = append(lines, strings.TrimPrefix(strings.TrimPrefix(line, "//"), " "))
	}
	return strings.Join(lines, "\n"), nil
}

func generate() ([]byte, error) {
	modules := map[string]module{}
	scopes := map[string][]string{}
	for _, target := range []struct{ name, pkg, os, arch string }{
		{"Backlot CLI (darwin/arm64)", "./cmd/backlot", "darwin", "arm64"},
		{"Backlot CLI (linux/amd64)", "./cmd/backlot", "linux", "amd64"},
		{"optional acceptance application (darwin/arm64)", "./examples/release-acceptance", "darwin", "arm64"},
		{"optional acceptance application (linux/arm64 container)", "./examples/release-acceptance", "linux", "arm64"},
	} {
		command := exec.Command("go", "list", "-deps", "-json", target.pkg)
		command.Env = append(os.Environ(), "GOOS="+target.os, "GOARCH="+target.arch, "CGO_ENABLED=0")
		data, err := command.Output()
		if err != nil {
			return nil, fmt.Errorf("list %s dependencies: %w", target.name, err)
		}
		decoder := json.NewDecoder(bytes.NewReader(data))
		seen := map[string]bool{}
		for {
			var dep dependency
			err := decoder.Decode(&dep)
			if errors.Is(err, io.EOF) {
				break
			}
			if err != nil {
				return nil, err
			}
			if dep.Module != nil && dep.Module.Version != "" {
				modules[dep.Module.Path] = *dep.Module
				if !seen[dep.Module.Path] {
					scopes[dep.Module.Path] = append(scopes[dep.Module.Path], target.name)
					seen[dep.Module.Path] = true
				}
			}
		}
	}
	toolchainData, err := exec.Command("go", "env", "-json", "GOROOT", "GOVERSION").Output()
	if err != nil {
		return nil, err
	}
	var toolchain struct{ GOROOT, GOVERSION string }
	if err := json.Unmarshal(toolchainData, &toolchain); err != nil {
		return nil, err
	}
	modules["Go standard library"] = module{Path: "Go standard library", Version: toolchain.GOVERSION, Dir: toolchain.GOROOT}
	scopes["Go standard library"] = []string{"all inventories above"}
	var supplements []supplement
	if err := json.Unmarshal(supplementData, &supplements); err != nil {
		return nil, err
	}

	names := make([]string, 0, len(modules))
	for name := range modules {
		names = append(names, name)
	}
	sort.Strings(names)
	var output bytes.Buffer
	output.WriteString("# Third-party notices\n\nGenerated by `go run ./cmd/notices` from pinned local module sources.\nIncludes packages linked into Backlot and its optional release acceptance\napplication, plus the Go standard library. Fixture image and browser licenses\nremain with their upstream distributions; they are not bundled with Backlot.\nInventories are labeled separately below. Reviewed embedded notices are version/source-bound in `cmd/notices/supplements.json`.\nDo not edit this generated file by hand.\n")
	for _, name := range names {
		m := modules[name]
		fmt.Fprintf(&output, "\n## %s %s\n\nLinked into: %s.\n", m.Path, m.Version, strings.Join(scopes[name], "; "))
		entries, err := os.ReadDir(m.Dir)
		if err != nil {
			return nil, err
		}
		found := false
		for _, entry := range entries {
			upper := strings.ToUpper(entry.Name())
			recognized := upper == "LICENSE" || strings.HasPrefix(upper, "LICENSE.") || upper == "NOTICE" || strings.HasPrefix(upper, "NOTICE.") || upper == "COPYING" || strings.HasPrefix(upper, "COPYING.")
			if entry.IsDir() || !recognized {
				continue
			}
			text, err := os.ReadFile(filepath.Join(m.Dir, entry.Name()))
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&output, "\n### %s\n\n```text\n%s\n```\n", entry.Name(), strings.TrimSpace(string(text)))
			found = true
		}
		for _, supplement := range supplements {
			if supplement.Module == m.Path {
				text, err := embeddedNotice(m, supplement)
				if err != nil {
					return nil, err
				}
				fmt.Fprintf(&output, "\n### Embedded notice: %s\n\n```text\n%s\n```\n", supplement.Source, text)
			}
		}

		if !found {
			return nil, fmt.Errorf("no license/notice found for %s", m.Path)
		}
	}
	return output.Bytes(), nil
}

func run() error {
	check := flag.Bool("check", false, "Reject stale notices without writing")
	flag.Parse()
	data, err := generate()
	if err != nil {
		return err
	}
	const path = "THIRD_PARTY_NOTICES.md"
	if *check {
		existing, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, data) {
			return errors.New("notices are stale; run go run ./cmd/notices")
		}
		return nil
	}
	return os.WriteFile(path, data, 0644)
}
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
