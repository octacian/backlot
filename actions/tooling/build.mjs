import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('.', import.meta.url)));
const check = process.argv.includes('--check');
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const result = await build({
  entryPoints: ['sdk.mjs'], bundle: true, minifyWhitespace: true, minifySyntax: true,
  platform: 'node', format: 'esm', outfile: '../setup/sdk.mjs',
  banner: { js: "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
  metafile: true, write: false,
});

// Resolve the installation boundary, not nested ESM/CJS package.json files.
const roots = new Set();
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, info] of Object.entries(output.inputs)) {
    if (!info.bytesInOutput || !input.includes('node_modules/')) continue;
    const parts = input.split('/');
    const start = parts.lastIndexOf('node_modules') + 1;
    roots.add(parts.slice(0, start + (parts[start].startsWith('@') ? 2 : 1)).join('/'));
  }
}

// Include nested third-party legal files too (for example undici's fetch license).
async function legalFiles(root, relative = '') {
  const files = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const name = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...await legalFiles(root, name));
    else if (entry.isFile() && /^(licen[cs]e|notice|copying|copyright)([.-]|$)/i.test(entry.name)) files.push(name);
  }
  return files.sort();
}

// Exact-version supplements cover npm archives that omit their license texts.
const supplements = {
  '@nodable/entities@3.1.0': 'licenses/nodable-entities-3.1.0.txt',
  'binary@0.3.0': 'licenses/binary-0.3.0.txt',
  'buffers@0.1.1': 'licenses/buffers-0.1.1.txt',
  'chainsaw@0.1.0': 'licenses/chainsaw-0.1.0.txt',
};
let notices = '# Native action SDK third-party notices\n\nGenerated by actions/tooling/build.mjs from packages contributing bytes to sdk.mjs.\nPackage paths and integrity values refer to actions/tooling/package-lock.json.\nBuild-only dependencies are excluded. Keep this file with actions/setup/sdk.mjs.\nThe root THIRD_PARTY_NOTICES.md separately covers Go dependencies.\n';
const packages = [];
for (const root of [...roots].sort()) {
  const pkg = JSON.parse(await readFile(`${root}/package.json`, 'utf8'));
  const id = `${pkg.name}@${pkg.version}`;
  if (lock.packages[root]?.version !== pkg.version || !lock.packages[root]?.integrity) throw new Error(`Unbound package: ${root}`);
  const files = await legalFiles(root);
  const texts = [];
  for (const file of files) texts.push([file, await readFile(`${root}/${file}`, 'utf8')]);
  if (supplements[id]) texts.push([supplements[id], await readFile(supplements[id], 'utf8')]);
  if (id === 'isarray@1.0.0') {
    const readme = await readFile(`${root}/README.md`, 'utf8');
    const start = readme.indexOf('## License');
    if (start < 0) throw new Error(`Missing README license: ${id}`);
    texts.push(['README.md (License section)', readme.slice(start)]);
  }
  if (!texts.length) throw new Error(`Missing license text: ${id} (${root})`);
  notices += `\n## ${id}\n\nPackage: ${root}\nIntegrity: ${lock.packages[root].integrity}\n`;
  for (const [source, text] of texts) notices += `\n### ${source}\n\n~~~~text\n${text.trimEnd()}\n~~~~\n`;
  packages.push({ name: pkg.name, version: pkg.version, path: root, integrity: lock.packages[root].integrity, notices: texts.map(([source]) => source) });
}
const outputs = [
  ['../setup/sdk.mjs', result.outputFiles[0].contents],
  ['../setup/SDK_NOTICES.md', notices],
  ['../setup/sdk-packages.json', JSON.stringify(packages, null, 2) + '\n'],
];
// Generate everything before touching committed outputs so missing notices fail closed.
for (const [file, content] of outputs) {
  if (check) {
    const expected = Buffer.from(content);
    if (!(await readFile(file)).equals(expected)) throw new Error(`Stale generated file: ${file}`);
  } else await writeFile(file, content);
}
console.log(`${check ? 'Verified' : 'Generated'} SDK and notices for ${packages.length} bundled package installations`);
